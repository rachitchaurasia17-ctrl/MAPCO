#!/usr/bin/env node
/* MAPCO — Property Intelligence · prompt codegen.
   The finalized prompt WORDING lives in the .txt files under
   src/packages/property-intelligence/prompts/. Those files are the single
   source of truth and must not be edited by code. This script embeds them
   verbatim into a runtime-neutral TypeScript module (the package is shared by
   the browser, Node and Deno, none of which agree on how to read a file), and
   records a sha256 of each so a persisted generation can be tied to the exact
   prompt that produced it.

   Run:  node scripts/sync-pi-prompts.mjs
   CI/test: tests/property-intelligence-prompts.test.ts fails if this module
   has drifted from the .txt files. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = resolve(here, '..', 'src', 'packages', 'property-intelligence', 'prompts');

/** Read with LF normalisation so the hash is stable across platforms. */
export function readPrompt(name) {
  return readFileSync(resolve(dir, name), 'utf8').replace(/\r\n/g, '\n');
}
export const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');

const phase1 = readPrompt('phase1.txt');
const phase2 = readPrompt('phase2.txt');

const out = `/* ═══════════════════════════════════════════════════════════════
   MAPCO — Property Intelligence · finalized prompts (GENERATED)
   ---------------------------------------------------------------
   DO NOT EDIT. Generated by v2/scripts/sync-pi-prompts.mjs from the
   canonical wording in ./phase1.txt and ./phase2.txt, which are the
   single source of truth for the finalized Property Intelligence
   architecture. Change the .txt, then re-run the script.

   tests/property-intelligence-prompts.test.ts fails if this file has
   drifted from the .txt files, so the two can never disagree.
   ═══════════════════════════════════════════════════════════════ */

/** Phase 1 — Gemini + Google Maps grounding, high-recall discovery.
 *  Placeholders: {{LATITUDE}} {{LONGITUDE}} {{LOCALITY}} {{CITY}} */
export const PHASE1_PROMPT_TEMPLATE: string = ${JSON.stringify(phase1)};

/** Phase 2 — final AI judge over the normalized candidate universe. */
export const PHASE2_PROMPT: string = ${JSON.stringify(phase2)};

/** sha256 of the exact prompt text, persisted with every generation so a
 *  stored result can be tied to the wording that produced it, and so a
 *  prompt edit naturally invalidates the cache. */
export const PHASE1_PROMPT_SHA256 = ${JSON.stringify(sha256(phase1))};
export const PHASE2_PROMPT_SHA256 = ${JSON.stringify(sha256(phase2))};

/** Short, human-readable prompt versions for logs and stored rows. */
export const PHASE1_PROMPT_VERSION = 'p1-' + PHASE1_PROMPT_SHA256.slice(0, 12);
export const PHASE2_PROMPT_VERSION = 'p2-' + PHASE2_PROMPT_SHA256.slice(0, 12);

/** Fill the Phase 1 template with the real canonical property. */
export function buildPhase1Prompt(input: {
  latitude: number; longitude: number; locality: string; city: string;
}): string {
  return PHASE1_PROMPT_TEMPLATE
    .replaceAll('{{LATITUDE}}', String(input.latitude))
    .replaceAll('{{LONGITUDE}}', String(input.longitude))
    .replaceAll('{{LOCALITY}}', input.locality || 'the surrounding locality')
    .replaceAll('{{CITY}}', input.city || 'the surrounding city');
}
`;

writeFileSync(resolve(dir, 'index.ts'), out, 'utf8');
console.log('wrote prompts/index.ts');
console.log('  phase1 sha256', sha256(phase1));
console.log('  phase2 sha256', sha256(phase2));
