describe('render-side guards', () => {
  it('parses a well-formed snapshot', () => {
    const parsed = parseIntelligenceSnapshot(validSnapshot);
    expect(parsed).not.toBeNull();
    expect(parsed!.signals).toHaveLength(1);
    expect(parsed!.recommendations[0]!.priority).toBe('now');
  });

  it('returns null rather than throwing on malformed input', () => {
    for (const bad of [null, undefined, 42, 'text', [], {}, { headline: 123 }]) {
      expect(parseIntelligenceSnapshot(bad)).toBeNull();
    }
  });

  it('drops undeclared keys from a stored payload', () => {
    const parsed = parseIntelligenceSnapshot({ ...validSnapshot, injected: '<script>' })!;
    expect('injected' in parsed).toBe(false);
  });

  it('falls back to a safe enum value instead of rendering an unknown one', () => {
    const parsed = parseIntelligenceSnapshot({
      ...validSnapshot,
      signals: [{ ...validSnapshot.signals[0], kind: 'made_up', direction: 'sideways', confidence: 'total' }],
    })!;
    expect(parsed.signals[0]!.kind).toBe('no_change');
    expect(parsed.signals[0]!.direction).toBe('flat');
    expect(parsed.signals[0]!.confidence).toBe('low');
  });

  it('drops evidence entries with no fact path', () => {
    const parsed = parseIntelligenceSnapshot({
      ...validSnapshot,
      signals: [{ ...validSnapshot.signals[0], evidence: [{ metric: 'opens', value: 1 }] }],
    })!;
    expect(parsed.signals[0]!.evidence).toHaveLength(0);
  });

  it('parses each remaining payload kind and rejects junk', () => {
    expect(parseSignalSet({ periodLabel: 'p', summary: 's', signals: [], insufficientData: true })).not.toBeNull();
    expect(parseWeeklyReport({
      periodLabel: '2026-W33', headline: 'h', executiveSummary: 's',
      sections: [], recommendations: [], insufficientData: false, dataNotes: [],
    })).not.toBeNull();
    expect(parseGeneratedCopy({ headline: 'h', caption: 'c', hashtags: [], callToAction: 'x', factsUsed: [] })).not.toBeNull();
    expect(parseGeneratedCopy({ headline: 'h' })).toBeNull();
    expect(parseMarketingSuggestion({ propertyId: 'p1', angle: 'value', rationale: 'r', confidence: 'low', channels: [], copy: { headline: 'h', caption: 'c', hashtags: [], callToAction: 'x', factsUsed: [] } })).not.toBeNull();
    expect(parseAnswer({ answer: 'a', answered: true, evidence: [], followUps: [] })).not.toBeNull();
    expect(parseAnswer({ answered: true })).toBeNull();
  });

  it('rejects an artifact envelope whose payload fails validation', () => {
    expect(parseArtifact({
      id: 'a1', kind: 'intelligence_snapshot', periodKey: '2026-08-12',
      version: 1, schemaVersion: 'v1', generatedAt: '2026-08-12T00:00:00Z',
      payload: { nope: true },
    }, PAYLOAD_PARSERS.intelligence_snapshot)).toBeNull();
  });

  it('keeps provenance available for auditing', () => {
    const artifact = parseArtifact({
      id: 'a1', kind: 'intelligence_snapshot', periodKey: '2026-08-12',
      version: 2, schemaVersion: 'v1', generatedAt: '2026-08-12T00:00:00Z',
      payload: validSnapshot,
      provenance: { provider: 'openai', model: 'gpt-4.1-mini', contextDigest: 'a'.repeat(64) },
    }, PAYLOAD_PARSERS.intelligence_snapshot)!;
    expect(artifact.version).toBe(2);
    expect(artifact.provenance.provider).toBe('openai');
  });
});

/* ═══════════════════════════════════════════════════════════════
   6. FAILURE BOUNDARY
   ═══════════════════════════════════════════════════════════════ */

describe('AI failure never breaks a surface', () => {
  it('turns a thrown adapter into an unavailable value', async () => {
    const result = await withAiFallback(async () => { throw new Error('backend down'); });
    expect(result).toEqual({ kind: 'unavailable', reason: 'error' });
  });

  it('maps repository error codes onto availability reasons', async () => {
    expect(await withAiFallback(async () => err('unauthorized', 'x')))
      .toEqual({ kind: 'unavailable', reason: 'not_authenticated' });
    expect(await withAiFallback(async () => err('forbidden', 'x')))
      .toEqual({ kind: 'unavailable', reason: 'disabled' });
    expect(await withAiFallback(async () => err('rate_limited', 'x')))
      .toEqual({ kind: 'unavailable', reason: 'quota_exceeded' });
  });

  it('gives up rather than hanging a page', async () => {
    const result = await withAiFallback(
      () => new Promise(() => { /* never settles */ }),
      { timeoutMs: 20 },
    );
    expect(result.kind).toBe('unavailable');
  });

  it('passes a successful read straight through', async () => {
    const artifact = parseArtifact({
      id: 'a1', kind: 'intelligence_snapshot', periodKey: 'p', version: 1,
      schemaVersion: 'v1', generatedAt: '2026-08-12T00:00:00Z', payload: validSnapshot,
    }, PAYLOAD_PARSERS.intelligence_snapshot)!;
    const result = await withAiFallback(async () => ok({ kind: 'ready' as const, artifact }));
    expect(shouldRenderAi(result)).toBe(true);
  });

  it('does not render an unavailable value', () => {
    expect(shouldRenderAi(aiUnavailable('disabled'))).toBe(false);
  });

  it('flags an insufficient-data payload as a quiet state', () => {
    expect(isInsufficient({ insufficientData: true })).toBe(true);
    expect(isInsufficient(validSnapshot)).toBe(false);
    expect(isInsufficient(null)).toBe(false);
  });
});

