describe('no dealer or presentation surface consumes AI yet', () => {
  function walk(dir: string): string[] {
    const out: string[] = [];
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) out.push(...walk(full));
      else if (/\.ts$/.test(name)) out.push(full);
    }
    return out;
  }

  it('only the internal AI console reads adapter.ai', () => {
    const consumers = walk(join(v2Root, 'src/apps'))
      .filter((file) => /adapter\.ai\b/.test(readFileSync(file, 'utf8')))
      .map((file) => file.replace(/\\/g, '/').split('/src/apps/')[1]);
    expect(consumers).toEqual(['ai-console/main.ts']);
  });

  it('the AI console is not linked from the dealer navigation', () => {
    const shell = readFileSync(join(v2Root, 'src/apps/dealer/shell.ts'), 'utf8');
    expect(shell).not.toContain('ai-console');
  });
});

