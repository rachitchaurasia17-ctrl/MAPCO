describe('schema DSL', () => {
  const schema = S.object({
    title: S.string({ maxLength: 10 }),
    count: S.number({ integer: true, min: 0 }),
    mode: S.enum(['a', 'b']),
    tags: S.array(S.string({ maxLength: 4 }), 2),
    note: S.string({ maxLength: 5 }),
  }, { optional: ['note'] });

  it('projects a strict JSON Schema providers can enforce', () => {
    const json = toJsonSchema(schema) as Record<string, unknown>;
    expect(json.additionalProperties).toBe(false);
    // Strict structured output requires every property to be listed.
    expect(json.required).toEqual(['title', 'count', 'mode', 'tags', 'note']);
    const properties = json.properties as Record<string, { type: unknown }>;
    expect(properties.note.type).toEqual(['string', 'null']);
    expect(properties.title.type).toBe('string');
  });

  it('accepts a valid value and strips undeclared keys', () => {
    const result = validate(schema, {
      title: 'ok', count: 3, mode: 'b', tags: ['x'], note: null,
      smuggled: 'should not survive',
    });
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.value).toEqual({ title: 'ok', count: 3, mode: 'b', tags: ['x'] });
      expect('smuggled' in (result.value as object)).toBe(false);
    }
  });

  it('rejects a missing required field', () => {
    const result = validate(schema, { count: 1, mode: 'a', tags: [] });
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.errors.join(' ')).toContain('$.title');
  });

  it('rejects a wrong type and an unknown enum value', () => {
    const result = validate(schema, { title: 'x', count: 'nope', mode: 'z', tags: [] });
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.errors.join(' ')).toContain('$.count');
      expect(result.errors.join(' ')).toContain('$.mode');
    }
  });

  it('caps an over-long array and trims an over-long string', () => {
    const result = validate(schema, {
      title: 'abcdefghijklmno', count: 1, mode: 'a', tags: ['1', '2', '3', '4'],
    });
    expect(result.ok).toBe(true);
    if (result.ok) {
      const value = result.value as { title: string; tags: string[] };
      expect(value.title).toHaveLength(10);
      expect(value.tags).toHaveLength(2);
    }
  });

  it('rejects a non-object payload outright', () => {
    expect(validate(schema, 'not an object').ok).toBe(false);
    expect(validate(schema, null).ok).toBe(false);
    expect(validate(schema, [1, 2]).ok).toBe(false);
  });
});

